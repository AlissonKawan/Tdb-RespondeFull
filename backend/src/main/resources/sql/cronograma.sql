-- Apenas para ambientes sem a tabela existente. Nao recriar a tabela em uso.
-- DATA_ATIVIDADE e horarios permanecem texto, como no contrato do cronograma.
CREATE TABLE T_TAREFA_CRONOGRAMA (
    ID_TAREFA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_VOLUNTARIO NUMBER NOT NULL,
    TIPO VARCHAR2(100) NOT NULL,
    DIA_SEMANA VARCHAR2(20) NOT NULL,
    TITULO VARCHAR2(255) NOT NULL,
    DESCRICAO VARCHAR2(4000),
    STATUS VARCHAR2(30) DEFAULT 'Pendente' NOT NULL,
    PRIORIDADE VARCHAR2(20) NOT NULL,
    DATA_ATIVIDADE VARCHAR2(20),
    HORA_INICIO VARCHAR2(10),
    HORA_FIM VARCHAR2(10),
    DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DATA_ATUALIZACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_CRONOGRAMA_VOL ON T_TAREFA_CRONOGRAMA(ID_VOLUNTARIO);
