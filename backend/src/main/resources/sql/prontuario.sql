CREATE TABLE PRONTUARIO (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    VOLUNTARIO_ID NUMBER NOT NULL,
    AGENDA_ID NUMBER,
    ATENDIMENTO_ID NUMBER,
    PACIENTE VARCHAR2(255) NOT NULL,
    HISTORICO_MEDICO VARCHAR2(1000),
    TRATAMENTO_ATUAL VARCHAR2(2000),
    DATA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PRONTUARIO_ATENDIMENTO FOREIGN KEY (ATENDIMENTO_ID) REFERENCES ATENDIMENTO(ID) ON DELETE SET NULL
);

CREATE INDEX IDX_PRONTUARIO_VOL ON PRONTUARIO(VOLUNTARIO_ID);
CREATE INDEX IDX_PRONTUARIO_AGE ON PRONTUARIO(AGENDA_ID);
CREATE INDEX IDX_PRONTUARIO_ATEND ON PRONTUARIO(ATENDIMENTO_ID);

