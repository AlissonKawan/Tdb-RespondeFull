-- Tabela central de autenticacao e tipo de usuario.
CREATE TABLE T_CONTA_USUARIO (
    ID_CONTA      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    NOME          VARCHAR2(120) NOT NULL,
    EMAIL         VARCHAR2(160) NOT NULL,
    SENHA_HASH    VARCHAR2(255) NOT NULL,
    TIPO_USUARIO  VARCHAR2(30)  NOT NULL,
    ATIVO         NUMBER(1) DEFAULT 1 NOT NULL,
    DATA_CRIACAO  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_CONTA_USUARIO PRIMARY KEY (ID_CONTA),
    CONSTRAINT UK_CONTA_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_CONTA_TIPO CHECK (TIPO_USUARIO IN ('VOLUNTARIO', 'BENEFICIARIO', 'ADMIN')),
    CONSTRAINT CK_CONTA_ATIVO CHECK (ATIVO IN (0, 1))
);

-- Canais usados na origem do atendimento e nas mensagens.
CREATE TABLE CANAL_COMUNICACAO (
    ID         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    NOME       VARCHAR2(50) NOT NULL,
    DESCRICAO  VARCHAR2(200),

    CONSTRAINT PK_CANAL_COMUNICACAO PRIMARY KEY (ID),
    CONSTRAINT UK_CANAL_NOME UNIQUE (NOME)
);

-- Especialidades que podem ser associadas aos voluntarios.
CREATE TABLE ESPECIALIDADE (
    ID         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    NOME       VARCHAR2(50) NOT NULL,
    DESCRICAO  VARCHAR2(200),

    CONSTRAINT PK_ESPECIALIDADE PRIMARY KEY (ID),
    CONSTRAINT UK_ESPECIALIDADE_NOME UNIQUE (NOME)
);

-- Perfil especifico do voluntario. Os campos USUARIO e SENHA sao legados
-- e permanecem porque o backend ainda mapeia essas colunas.
CREATE TABLE VOLUNTARIO (
    ID                    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    NOME                  VARCHAR2(100) NOT NULL,
    USUARIO               VARCHAR2(50) NOT NULL,
    SENHA                 VARCHAR2(255) NOT NULL,
    ACESSO_SIGILO         NUMBER(1) DEFAULT 0 NOT NULL,
    DISPONIVEL            NUMBER(1) DEFAULT 1 NOT NULL,
    ID_CONTA              NUMBER,
    STATUS_APROVACAO      VARCHAR2(30) DEFAULT 'PENDENTE' NOT NULL,
    MOTIVO_VOLUNTARIADO   VARCHAR2(1000),
    CRO                   VARCHAR2(30),
    UF_CRO                VARCHAR2(2),
    STATUS_CRO            VARCHAR2(50),

    CONSTRAINT PK_VOLUNTARIO PRIMARY KEY (ID),
    CONSTRAINT UK_VOLUNTARIO_CONTA UNIQUE (ID_CONTA),
    CONSTRAINT FK_VOL_CONTA FOREIGN KEY (ID_CONTA)
        REFERENCES T_CONTA_USUARIO (ID_CONTA),
    CONSTRAINT CK_VOL_ACESSO_SIGILO CHECK (ACESSO_SIGILO IN (0, 1)),
    CONSTRAINT CK_VOL_DISPONIVEL CHECK (DISPONIVEL IN (0, 1)),
    CONSTRAINT CK_VOL_STATUS_APROVACAO CHECK (STATUS_APROVACAO IN ('PENDENTE', 'APROVADO', 'RECUSADO'))
);

-- Pessoa atendida pelo projeto. Pode representar crianca/adolescente,
-- mulher Apolonia ou outro beneficiario.
CREATE TABLE PESSOA_ATENDIDA (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    NOME_CODIFICADO  VARCHAR2(100) NOT NULL,
    DATA_CADASTRO    DATE DEFAULT SYSDATE NOT NULL,
    TELEFONE         VARCHAR2(20),
    EMAIL            VARCHAR2(100),
    TIPO             VARCHAR2(30) NOT NULL,
    ID_CONTA         NUMBER,

    CONSTRAINT PK_PESSOA_ATENDIDA PRIMARY KEY (ID),
    CONSTRAINT UK_PESSOA_ATENDIDA_CONTA UNIQUE (ID_CONTA),
    CONSTRAINT FK_PESSOA_CONTA FOREIGN KEY (ID_CONTA)
        REFERENCES T_CONTA_USUARIO (ID_CONTA),
    CONSTRAINT CK_PESSOA_TIPO CHECK (TIPO IN ('CRIANCA_ADOLESCENTE', 'MULHER_APOLONIA', 'OUTRO'))
);

-- Dados complementares para criancas e adolescentes.
CREATE TABLE CRIANCA_ADOLESCENTE (
    PESSOA_ID         NUMBER,
    IDADE             NUMBER NOT NULL,
    NOME_RESPONSAVEL  VARCHAR2(100),
    ESCOLA            VARCHAR2(100),
    GRAVIDADE_BUCAL   NUMBER NOT NULL,

    CONSTRAINT PK_CRIANCA PRIMARY KEY (PESSOA_ID),
    CONSTRAINT FK_CRIANCA_PESSOA FOREIGN KEY (PESSOA_ID)
        REFERENCES PESSOA_ATENDIDA (ID)
        ON DELETE CASCADE,
    CONSTRAINT CK_CRIANCA_IDADE CHECK (IDADE BETWEEN 0 AND 17),
    CONSTRAINT CK_CRIANCA_GRAVIDADE CHECK (GRAVIDADE_BUCAL BETWEEN 1 AND 5)
);

-- Dados complementares para o programa Apolonia.
CREATE TABLE MULHER_APOLONIA (
    PESSOA_ID                   NUMBER,
    CODINOME                    VARCHAR2(50),
    NIVEL_RISCO                 NUMBER NOT NULL,
    TEM_BOLETIM_OCORRENCIA      NUMBER(1) DEFAULT 0 NOT NULL,
    NECESSITA_SIGILO_ABSOLUTO   NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_MULHER PRIMARY KEY (PESSOA_ID),
    CONSTRAINT FK_MULHER_PESSOA FOREIGN KEY (PESSOA_ID)
        REFERENCES PESSOA_ATENDIDA (ID)
        ON DELETE CASCADE,
    CONSTRAINT CK_MULHER_RISCO CHECK (NIVEL_RISCO BETWEEN 1 AND 5),
    CONSTRAINT CK_MULHER_BO CHECK (TEM_BOLETIM_OCORRENCIA IN (0, 1)),
    CONSTRAINT CK_MULHER_SIGILO CHECK (NECESSITA_SIGILO_ABSOLUTO IN (0, 1))
);

-- Atendimento operacional do projeto.
CREATE TABLE ATENDIMENTO (
    ID                    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    PESSOA_ATENDIDA_ID    NUMBER NOT NULL,
    VOLUNTARIO_ID         NUMBER,
    CANAL_COMUNICACAO_ID  NUMBER NOT NULL,
    PRIORIDADE            NUMBER DEFAULT 3 NOT NULL,
    STATUS                VARCHAR2(50) DEFAULT 'ABERTO' NOT NULL,
    DATA_ABERTURA         DATE DEFAULT SYSDATE NOT NULL,
    DATA_ENCERRAMENTO     DATE,
    DESCRICAO             VARCHAR2(1000),

    CONSTRAINT PK_ATENDIMENTO PRIMARY KEY (ID),
    CONSTRAINT FK_AT_PESSOA FOREIGN KEY (PESSOA_ATENDIDA_ID)
        REFERENCES PESSOA_ATENDIDA (ID),
    CONSTRAINT FK_AT_VOLUNTARIO FOREIGN KEY (VOLUNTARIO_ID)
        REFERENCES VOLUNTARIO (ID),
    CONSTRAINT FK_AT_CANAL FOREIGN KEY (CANAL_COMUNICACAO_ID)
        REFERENCES CANAL_COMUNICACAO (ID),
    CONSTRAINT CK_AT_PRIORIDADE CHECK (PRIORIDADE BETWEEN 1 AND 5),
    CONSTRAINT CK_AT_STATUS CHECK (STATUS IN ('ABERTO', 'EM_ATENDIMENTO', 'ENCERRADO', 'CANCELADO')),
    CONSTRAINT CK_AT_DATA_ENC CHECK (DATA_ENCERRAMENTO IS NULL OR DATA_ENCERRAMENTO >= DATA_ABERTURA)
);

-- Mensagens vinculadas ao atendimento.
CREATE TABLE MENSAGEM (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    ATENDIMENTO_ID  NUMBER NOT NULL,
    CONTEUDO        CLOB NOT NULL,
    DATA_HORA       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ENVIADO_POR     VARCHAR2(50) NOT NULL,

    CONSTRAINT PK_MENSAGEM PRIMARY KEY (ID),
    CONSTRAINT FK_MSG_ATEND FOREIGN KEY (ATENDIMENTO_ID)
        REFERENCES ATENDIMENTO (ID)
        ON DELETE CASCADE,
    CONSTRAINT CK_MSG_ENVIADO_POR CHECK (ENVIADO_POR IN ('BENEFICIARIO', 'VOLUNTARIO', 'ADMIN'))
);

-- Associacao entre mensagem e canal.
CREATE TABLE MENSAGEM_CANAL (
    MENSAGEM_ID  NUMBER NOT NULL,
    CANAL_ID     NUMBER NOT NULL,

    CONSTRAINT PK_MSG_CANAL PRIMARY KEY (MENSAGEM_ID, CANAL_ID),
    CONSTRAINT FK_MC_MSG FOREIGN KEY (MENSAGEM_ID)
        REFERENCES MENSAGEM (ID)
        ON DELETE CASCADE,
    CONSTRAINT FK_MC_CANAL FOREIGN KEY (CANAL_ID)
        REFERENCES CANAL_COMUNICACAO (ID)
);

-- Historico de alteracao de status do atendimento.
CREATE TABLE HISTORICO_STATUS (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    ATENDIMENTO_ID    NUMBER NOT NULL,
    STATUS_ANTERIOR   VARCHAR2(50),
    STATUS_NOVO       VARCHAR2(50) NOT NULL,
    ALTERADO_POR_ID   NUMBER,
    DATA_HORA         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_HIST_STATUS PRIMARY KEY (ID),
    CONSTRAINT FK_HIST_AT FOREIGN KEY (ATENDIMENTO_ID)
        REFERENCES ATENDIMENTO (ID)
        ON DELETE CASCADE,
    CONSTRAINT FK_HIST_VOL FOREIGN KEY (ALTERADO_POR_ID)
        REFERENCES VOLUNTARIO (ID),
    CONSTRAINT CK_HIST_STATUS_ANT CHECK (
        STATUS_ANTERIOR IS NULL OR STATUS_ANTERIOR IN ('ABERTO', 'EM_ATENDIMENTO', 'ENCERRADO', 'CANCELADO')
    ),
    CONSTRAINT CK_HIST_STATUS_NOVO CHECK (
        STATUS_NOVO IN ('ABERTO', 'EM_ATENDIMENTO', 'ENCERRADO', 'CANCELADO')
    )
);

-- Relacionamento N:N entre voluntarios e especialidades.
CREATE TABLE VOLUNTARIO_ESPECIALIDADE (
    VOLUNTARIO_ID     NUMBER NOT NULL,
    ESPECIALIDADE_ID  NUMBER NOT NULL,

    CONSTRAINT PK_VOL_ESP PRIMARY KEY (VOLUNTARIO_ID, ESPECIALIDADE_ID),
    CONSTRAINT FK_VE_VOL FOREIGN KEY (VOLUNTARIO_ID)
        REFERENCES VOLUNTARIO (ID)
        ON DELETE CASCADE,
    CONSTRAINT FK_VE_ESP FOREIGN KEY (ESPECIALIDADE_ID)
        REFERENCES ESPECIALIDADE (ID)
        ON DELETE CASCADE
);

-- Indices auxiliares para consultas por chaves estrangeiras.
CREATE INDEX IDX_AT_PESSOA ON ATENDIMENTO (PESSOA_ATENDIDA_ID);
CREATE INDEX IDX_AT_VOLUNTARIO ON ATENDIMENTO (VOLUNTARIO_ID);
CREATE INDEX IDX_AT_CANAL ON ATENDIMENTO (CANAL_COMUNICACAO_ID);
CREATE INDEX IDX_MSG_ATEND ON MENSAGEM (ATENDIMENTO_ID);
CREATE INDEX IDX_HIST_AT ON HISTORICO_STATUS (ATENDIMENTO_ID);
CREATE INDEX IDX_HIST_VOL ON HISTORICO_STATUS (ALTERADO_POR_ID);

-- View util para administracao de voluntarios.
CREATE OR REPLACE VIEW VW_VOLUNTARIO_COMPLETO AS
SELECT
    V.ID AS VOLUNTARIO_ID,
    V.ID_CONTA,
    C.NOME AS NOME_CONTA,
    V.NOME AS NOME_VOLUNTARIO,
    C.EMAIL,
    C.TIPO_USUARIO,
    C.ATIVO,
    V.ACESSO_SIGILO,
    V.DISPONIVEL,
    V.STATUS_APROVACAO,
    V.MOTIVO_VOLUNTARIADO,
    C.DATA_CRIACAO
FROM VOLUNTARIO V
JOIN T_CONTA_USUARIO C
    ON C.ID_CONTA = V.ID_CONTA;
