-- Conferir schema real, backup e nomes das constraints antes de executar.
-- DDL Oracle faz commit implicito: ROLLBACK nao desfaz estes comandos.
-- Sem backfill: contas existentes continuam acessando por email.

ALTER TABLE T_CONTA_USUARIO ADD (
    USUARIO VARCHAR2(40),
    TIPO_BENEFICIARIO VARCHAR2(30),
    MODO_IDENTIFICACAO VARCHAR2(16)
);
ALTER TABLE T_CONTA_USUARIO MODIFY (EMAIL NULL);
CREATE UNIQUE INDEX UK_CONTA_USUARIO_LOGIN ON T_CONTA_USUARIO (LOWER(USUARIO));
ALTER TABLE T_CONTA_USUARIO ADD CONSTRAINT CK_CONTA_PROGRAMA
    CHECK (TIPO_BENEFICIARIO IN ('MULHER_APOLONIA', 'CRIANCA_ADOLESCENTE'));
ALTER TABLE T_CONTA_USUARIO ADD CONSTRAINT CK_CONTA_IDENTIFICACAO
    CHECK (MODO_IDENTIFICACAO IN ('NOME', 'CODINOME', 'GERADO'));
ALTER TABLE T_CONTA_USUARIO ADD CONSTRAINT CK_CONTA_ACESSO
    CHECK (EMAIL IS NOT NULL OR (
        TIPO_USUARIO = 'BENEFICIARIO'
        AND TIPO_BENEFICIARIO IS NOT NULL AND TIPO_BENEFICIARIO = 'MULHER_APOLONIA'
        AND USUARIO IS NOT NULL AND MODO_IDENTIFICACAO IS NOT NULL
    ));

-- NULL significa que a beneficiaria nao respondeu. 0 e 1 mantem seus significados.
-- Nenhum registro historico e reinterpretado ou alterado.
ALTER TABLE MULHER_APOLONIA MODIFY (TEM_BOLETIM_OCORRENCIA DEFAULT NULL NULL);

-- Verificacao apos execucao autorizada (somente metadados, sem dados pessoais):
SELECT TABLE_NAME, COLUMN_NAME, NULLABLE, DATA_TYPE, DATA_LENGTH
FROM USER_TAB_COLUMNS
WHERE (TABLE_NAME = 'T_CONTA_USUARIO'
       AND COLUMN_NAME IN ('USUARIO', 'EMAIL', 'TIPO_BENEFICIARIO', 'MODO_IDENTIFICACAO'))
   OR (TABLE_NAME = 'MULHER_APOLONIA' AND COLUMN_NAME = 'TEM_BOLETIM_OCORRENCIA');
