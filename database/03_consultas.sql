CREATE TABLE ATENDIMENTO (
    ID                    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PESSOA_ATENDIDA_ID    NUMBER NOT NULL,
    VOLUNTARIO_ID         NUMBER,
