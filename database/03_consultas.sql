CREATE OR REPLACE VIEW VW_VOLUNTARIO_COMPLETO AS
SELECT
    V.ID AS VOLUNTARIO_ID,
    V.ID_CONTA,
    C.NOME AS NOME_CONTA,
    V.NOME AS NOME_VOLUNTARIO,
    C.EMAIL,
    C.TIPO_USUARIO,
    C.ATIVO,
    V.ACESSO_SIGILO,
    V.DISPONIVEL,
    V.STATUS_APROVACAO,
    V.MOTIVO_VOLUNTARIADO,
    C.DATA_CRIACAO
FROM VOLUNTARIO V
JOIN T_CONTA_USUARIO C
    ON C.ID_CONTA = V.ID_CONTA;

