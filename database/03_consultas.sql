-- ============================================================
-- VOLUNTARIO
-- Regra principal:
-- - Login, email, senha e tipo ficam em T_CONTA_USUARIO.
-- - VOLUNTARIO guarda dados especÃ­ficos do voluntÃ¡rio.
-- - ID_CONTA faz a ligaÃ§Ã£o 1:1 com T_CONTA_USUARIO.
--
-- ObservaÃ§Ã£o:
-- USUARIO e SENHA foram mantidos como campos LEGADOS/compatibilidade,
-- porque seu backend antigo pode ainda referenciar essas colunas.
-- A autenticaÃ§Ã£o oficial deve usar T_CONTA_USUARIO.EMAIL + SENHA_HASH.
-- ============================================================

CREATE TABLE VOLUNTARIO (
    ID                    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CONTA              NUMBER NOT NULL,

    -- Campo de perfil/compatibilidade. Preferencialmente manter igual ao nome da conta.
    NOME                  VARCHAR2(100) NOT NULL,

    -- Campos legados. NÃ£o usar como fonte principal de login.
    USUARIO               VARCHAR2(50),
    SENHA                 VARCHAR2(255),

    ACESSO_SIGILO         NUMBER(1) DEFAULT 0 NOT NULL,
    DISPONIVEL            NUMBER(1) DEFAULT 1 NOT NULL,
    STATUS_APROVACAO      VARCHAR2(30) DEFAULT 'PENDENTE' NOT NULL,
    MOTIVO_VOLUNTARIADO   VARCHAR2(1000),

    CONSTRAINT PK_VOLUNTARIO PRIMARY KEY (ID),
    CONSTRAINT UK_VOL_CONTA UNIQUE (ID_CONTA),
    CONSTRAINT FK_VOL_CONTA FOREIGN KEY (ID_CONTA)
        REFERENCES T_CONTA_USUARIO (ID_CONTA),

    CONSTRAINT CK_VOL_ACESSO_SIGILO CHECK (ACESSO_SIGILO IN (0, 1)),
    CONSTRAINT CK_VOL_DISPONIVEL CHECK (DISPONIVEL IN (0, 1)),
    CONSTRAINT CK_VOL_STATUS_APROV CHECK (STATUS_APROVACAO IN ('PENDENTE', 'APROVADO', 'RECUSADO'))
);

