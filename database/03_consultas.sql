    DATA_ENCERRAMENTO     DATE,
    DESCRICAO             VARCHAR2(1000),

    CONSTRAINT PK_ATENDIMENTO PRIMARY KEY (ID),

    CONSTRAINT FK_AT_PESSOA FOREIGN KEY (PESSOA_ATENDIDA_ID)
        REFERENCES PESSOA_ATENDIDA (ID),

    CONSTRAINT FK_AT_VOLUNTARIO FOREIGN KEY (VOLUNTARIO_ID)
        REFERENCES VOLUNTARIO (ID),

    CONSTRAINT FK_AT_CANAL FOREIGN KEY (CANAL_COMUNICACAO_ID)
        REFERENCES CANAL_COMUNICACAO (ID),

